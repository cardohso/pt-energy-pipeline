"""Lineage diagram generated from the pipeline definition, never drawn by hand.

Nodes and edges come from the same objects the pipeline runs on: the dataset specs in
``transform.stage.SPECS`` (source, raw layer, parser, staging table), the contracts folder (one
contract per dataset), and the SQL that builds each modelled table (its inputs are read out of the
``FROM stg_<dataset>`` references). ``pt-energy lineage diagram`` writes ``docs/lineage.md`` and CI
fails if the committed file no longer matches the pipeline.
"""

from __future__ import annotations

import re
from pathlib import Path

from pt_energy.transform.model import MODELS
from pt_energy.transform.stage import SPECS

SOURCE_LABELS = {"omie": "OMIE", "eredes": "E-REDES", "entsoe": "ENTSO-E"}
HEADER = """# Lineage

Generated by `pt-energy lineage diagram` from the pipeline definition (dataset specs, contracts and
the SQL of each modelled table). Do not edit by hand: CI fails if this file is out of date.

## Pipeline

"""
FOOTER = """
Solid arrows are data. Dotted arrows are contracts: they define what the staging tables must look
like, and the quality gate generates its checks from them.

## From a number back to its raw file

Every modelled row carries `raw_sha256`. `meta.lineage` maps that hash to the raw file, when it was
fetched, the git SHA of the code, and the contract version:

```sql
SELECT p.interval_start_utc, p.price_eur_mwh, l.path, l.fetched_at, l.pipeline_version
FROM model.day_ahead_price p JOIN meta.lineage l ON l.content_sha256 = p.raw_sha256
WHERE p.source = 'omie' ORDER BY p.interval_start_utc DESC LIMIT 1;
```

The file at `l.path` (under the data folder) is the publisher's payload, byte for byte. OpenLineage
events for every build are written to `lineage/openlineage/<batch_id>.jsonl`.
"""


def _model_inputs() -> dict[str, list[str]]:
    return {
        name: sorted(set(re.findall(r"stg_(\w+?)\b", sql)) & {s.dataset for s in SPECS.values()})
        for name, sql in MODELS.items()
    }


def mermaid(contracts_dir: Path) -> str:
    contracts = sorted(p.stem for p in contracts_dir.glob("*.yaml"))
    lines = ["flowchart LR"]
    for src in sorted({s.source for s in SPECS.values()}):
        lines.append(f'  src_{src}(["{SOURCE_LABELS[src]}"])')
    lines.append("  subgraph raw [raw: immutable payloads + provenance]")
    for s in SPECS.values():
        lines.append(f'    raw_{s.dataset}["{s.dataset}"]')
    lines.append("  end")
    lines.append("  subgraph staging [staging: UTC rows, one table per dataset]")
    for s in SPECS.values():
        lines.append(f'    stg_{s.dataset}["{s.dataset}"]')
    lines.append("  end")
    lines.append("  subgraph model [model: one row per interval]")
    for name in MODELS:
        lines.append(f'    model_{name}["{name}"]')
    lines.append("  end")
    lines.append('  gate{{"quality gate"}}')
    lines.append('  serving[("serving: Parquet + DuckDB")]')
    lines.append('  held["previous build stays published"]')
    for s in SPECS.values():
        lines.append(f"  src_{s.source} --> raw_{s.dataset}")
        lines.append(f"  raw_{s.dataset} -->|{s.parser.__name__}| stg_{s.dataset}")
    for name, inputs in _model_inputs().items():
        for d in inputs:
            lines.append(f"  stg_{d} --> model_{name}")
    for name in MODELS:
        lines.append(f"  model_{name} --> gate")
    for c in contracts:
        if c in {s.dataset for s in SPECS.values()}:
            lines.append(f"  stg_{c} -.->|contract {c}| gate")
    lines.append("  gate -->|all blocking checks pass| serving")
    lines.append("  gate -->|a blocking check fails| held")
    return "\n".join(lines)


def render(contracts_dir: Path) -> str:
    return f"{HEADER}```mermaid\n{mermaid(contracts_dir)}\n```\n{FOOTER}"
